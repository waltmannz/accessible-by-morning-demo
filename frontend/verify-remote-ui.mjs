import {chromium} from 'playwright';
import axe from 'axe-core';
import {mkdir,writeFile} from 'node:fs/promises';
const origin=process.env.DEMO_URL||'http://127.0.0.1:4173';
const out='runs/ui-verification';await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const orphan={id:'ui-orphan',mode:'gemini',status:'interrupted',stage:'fix',events:[],remote:{fixer:{id:'mock-cloud-id',status:'in_progress',cancellationStatus:'HTTP 400'}}};
let blockers=[orphan],reconciliations=0,starts=0;
const respond=(route,data,status=200)=>route.fulfill({status,contentType:'application/json',body:JSON.stringify(data)});
await page.route('**/api/config',route=>respond(route,{geminiConfigured:true,defaultMode:'gemini',blockedManagedRuns:blockers}));
await page.route('**/api/runs/ui-orphan',route=>respond(route,orphan));
await page.route('**/api/runs/ui-orphan/reconcile',route=>{reconciliations++;if(reconciliations>1){orphan.remote.fixer.status='cancelled';orphan.remote.fixer.cancellationStatus='terminal confirmed';blockers=[];}return respond(route,orphan);});
await page.route('**/api/runs',route=>{if(route.request().method()==='POST')starts++;return respond(route,{runs:[]});});
const checks=[];const check=(name,passed)=>{checks.push({name,passed});if(!passed)throw new Error(name);};
await page.goto(origin,{waitUntil:'networkidle'});
check('Orphaned cloud run is visible on initial load',await page.locator('#remote-status-panel').isVisible());
check('Managed start disabled while cloud work unresolved',await page.locator('#start-run').isDisabled());
await page.evaluate(()=>document.getElementById('start-run').dispatchEvent(new MouseEvent('click',{bubbles:true})));
check('Start handler cannot silently create another managed run',starts===0);
await page.getByRole('button',{name:'View run',exact:true}).click();
await page.waitForFunction(()=>document.getElementById('run-status').textContent==='REMOTE UNRESOLVED');
check('Interrupted local loop is not shown as cancelled cloud work',!(await page.locator('#run-status').textContent()).includes('CANCELLED'));
await page.locator('input[name="mode"][value="local"]').check();
check('Local rehearsal remains available',await page.locator('#start-run').isEnabled());
await page.locator('input[name="mode"][value="gemini-api"]').check();
check('Direct Gemini API option remains available with managed orphan',await page.locator('#start-run').isEnabled());
check('Direct API copy describes model calls accurately',(await page.locator('#mode-note').textContent()).includes('Direct Gemini model calls'));
await page.locator('input[name="mode"][value="gemini"]').check();
await page.getByRole('button',{name:'Check cloud status',exact:true}).click();
await page.waitForFunction(()=>document.getElementById('run-action-note').textContent.includes('still active'));
check('Read-only reconciliation retains block for active remote status',await page.locator('#start-run').isDisabled());
await page.getByRole('button',{name:'Check cloud status',exact:true}).click();
await page.waitForFunction(()=>document.getElementById('remote-status-panel').hidden);
check('Confirmed terminal cloud status releases managed block',await page.locator('#start-run').isEnabled());
check('Only reconciliation requests occurred; no new agent run',reconciliations===2&&starts===0);
await page.evaluate(()=>renderRun({id:'ui-api-restored',mode:'gemini-api',status:'completed',stage:'complete',events:[]}));
check('Restored direct API run selects its own engine',await page.locator('input[name="mode"][value="gemini-api"]').isChecked());
check('Direct API results never claim hosted Managed Agent',(await page.locator('#run-engine').textContent())==='GEMINI API · SOURCE REPAIR + REVIEW');
const running={id:'ui-running',mode:'gemini',status:'running',stage:'fix',events:[],remote:{fixer:{id:'mock-running-id',status:'in_progress'}}};
await page.route('**/api/runs/ui-running/cancel',route=>respond(route,{id:running.id,status:'cancelling'},202));
await page.route('**/api/runs/ui-running',route=>respond(route,{...running,status:'cancelled',remote:{fixer:{id:'mock-running-id',status:'in_progress',cancellationStatus:'requested'}}}));
await page.evaluate(run=>renderRun(run),running);
await page.getByRole('button',{name:'Stop this run',exact:true}).click();
await page.waitForFunction(()=>document.getElementById('run-status').textContent==='REMOTE UNRESOLVED');
check('Local stop request never claims remote cancellation confirmed',(await page.locator('#run-action-note').textContent()).includes('unconfirmed'));
check('Unconfirmed cloud cancellation blocks next managed run',await page.locator('#start-run').isDisabled());
await page.addScriptTag({content:axe.source});
const audit=await page.evaluate(()=>axe.run({include:[['body']],exclude:[['iframe']]}));
check('Remote status controls have no axe findings',audit.violations.length===0);
await page.screenshot({path:`${out}/dashboard-remote-unresolved.png`,fullPage:true});
await page.setViewportSize({width:390,height:844});
check('Remote status panel has no mobile horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.screenshot({path:`${out}/dashboard-remote-unresolved-mobile.png`,fullPage:true});
await writeFile(`${out}/remote-ui-checks.json`,JSON.stringify({checks,reconciliations,starts,violations:audit.violations},null,2));
console.log(JSON.stringify({checks,reconciliations,starts},null,2));
await browser.close();
